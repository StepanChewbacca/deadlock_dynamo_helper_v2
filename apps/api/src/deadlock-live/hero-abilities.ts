// Flat set of ALL ability item_ids across all heroes (for fast lookup)
export const ALL_ABILITY_ITEM_IDS: Set<number> = new Set(
  Object.values(HERO_ABILITY_MAP).flatMap((m) => Object.keys(m).map(Number))
);

export function mapAbilityToSkillNumber(heroId: number, abilityItemId: number): number {
  const heroMap = HERO_ABILITY_MAP[heroId];
  if (heroMap && abilityItemId in heroMap) {
    return heroMap[abilityItemId];
  }
  return 1;
}

export function isAbilityItem(heroId: number, itemId: number): boolean {
  const heroMap = HERO_ABILITY_MAP[heroId];
  if (heroMap && itemId in heroMap) {
    return true;
  }
  return ALL_ABILITY_ITEM_IDS.has(itemId);
}
