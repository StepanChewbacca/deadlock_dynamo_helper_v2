// Flat set of all ability item IDs across all heroes. The crawler uses this to
// keep hero abilities out of the regular item build even when the ability does
// not belong to the player hero.
export const ALL_ABILITY_ITEM_IDS: Set<number> = new Set(
  Object.values(HERO_ABILITY_MAP).flatMap((map) => Object.keys(map).map(Number)),
);

export function mapAbilityToSkillNumber(heroId: number, abilityItemId: number): number {
  return HERO_ABILITY_MAP[heroId]?.[abilityItemId] ?? UNKNOWN_SKILL_SLOT;
}

export function isAbilityItem(heroId: number, itemId: number): boolean {
  return itemId in (HERO_ABILITY_MAP[heroId] ?? {}) || ALL_ABILITY_ITEM_IDS.has(itemId);
}
